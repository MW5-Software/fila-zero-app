# --- HTTPS ------------------------------------------------------------------
#
# `manage.py check --deploy` acusava quatro coisas, e todas as quatro têm o
# mesmo desfecho: o cookie de sessão viajando em texto claro. Quem estiver na
# mesma rede Wi-Fi de quem usa o portal copia o cookie e entra como a pessoa —
# sem senha, sem aviso, sem deixar rastro diferente de um acesso normal.
#
# **Ligadas fora de DEBUG, e só lá.** Em desenvolvimento a máquina serve
# `http://127.0.0.1`, e um cookie `Secure` simplesmente não é enviado: a tela
# de entrada aceitaria a senha e devolveria a tela de entrada, para sempre,
# sem dizer por quê. É a configuração que mais parece defeito do sistema.
if not DEBUG:
    # O cookie só viaja por HTTPS. Os dois, e não só o de sessão: o token
    # CSRF em claro deixa forjar requisição em nome de quem está logado.
    SESSION_COOKIE_SECURE = True
    CSRF_COOKIE_SECURE = True

    # `Lax` é o padrão do Django e está certo aqui — o portal não recebe POST
    # de outro site, e `Strict` quebraria o clique num link de e-mail.
    SESSION_COOKIE_SAMESITE = "Lax"
    CSRF_COOKIE_SAMESITE = "Lax"

    # JavaScript não lê o cookie de sessão. Não é o que impede XSS; é o que
    # impede um XSS de virar sessão roubada.
    SESSION_COOKIE_HTTPONLY = True

    # Quem chegar por `http://` é mandado para `https://`. O proxy do VPS já
    # faz isso hoje, e ter nos dois lugares é de propósito: o dia em que
    # alguém trocar o proxy, a aplicação continua recusando o texto claro.
    SECURE_SSL_REDIRECT = True

    # Como o Django descobre que a requisição chegou por HTTPS quando quem
    # termina o TLS é o proxy. **Sem esta linha, `SECURE_SSL_REDIRECT` acima
    # entra em laço infinito de redirecionamento**: a aplicação vê `http`,
    # manda para `https`, o proxy entrega em `http` de novo. Só é seguro
    # porque nada além do proxy fala com o container.
    SECURE_PROXY_SSL_HEADER = ("HTTP_X_FORWARDED_PROTO", "https")

    # HSTS: o navegador passa a recusar `http://` neste domínio por conta
    # própria, sem nem tentar. Um ano, o valor que a própria lista de
    # pré-carga do Chrome exige.
    #
    # **É a única linha aqui que não se desfaz mudando o código.** O navegador
    # de quem já visitou guarda a regra pelo prazo inteiro: se o domínio
    # precisar voltar a servir HTTP, essas pessoas ficam sem acesso até o
    # prazo vencer. Por isso o subdomínio fica de fora — ligar
    # `INCLUDE_SUBDOMAINS` sem certificado em todos os subdomínios derruba os
    # que ainda não têm.
    SECURE_HSTS_SECONDS = 31536000

    # O navegador não manda a URL de onde veio ao sair para outro site — e a
    # URL daqui carrega id de produto e de orçamento.
    SECURE_REFERRER_POLICY = "same-origin"


