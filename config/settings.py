# Havia aqui um caminho de SQLite quando `KRONOS_BANCO` estava vazio, para
# "não exigir serviço de pé em quem só quer rodar a suíte", e o comentário
# afirmava que o esquema era o mesmo nos dois. O ESQUEMA é; o comportamento
# não — transação, `CheckConstraint`, ordenação com acento, `distinct`,
# tipo de coluna. As vinte instalações rodam Postgres, e testar noutro banco
# é provar a coisa errada.
#
# O outro custo já apareceu antes deste: com os dois caminhos vivos, a mesma
# instalação tinha DOIS bancos — cadastrava-se num e olhava-se no outro,
# porque `runserver` sem a variável caía no SQLite sem avisar.
